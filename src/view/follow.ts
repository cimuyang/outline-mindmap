/**
 * 「这个导图该显示哪一篇笔记」的取舍规则。
 *
 * 单独一个零依赖的文件，是为了能直接单测：这条规则出过一次 bug，
 * 而它在真实环境里的触发条件（后台的叶子被卸载、再唤醒）手工很难复现。
 */

/**
 * 拿到一个「存档里的路径」时该显示哪一篇。
 *
 * 【默认活动笔记优先，存档路径只是回退】。1.7.2 起 Obsidian 会把不可见的叶子整个卸载
 * （后台标签页、收起的侧边栏里的导图）；卸载期间导图连监听器都不存在，你换过几篇笔记
 * 它一无所知。等你把它露出来，视图重建、`setState` 带回来的是【卸载那一刻】存下的路径——
 * 无条件采信，导图就停在上一篇了，而且不会自愈：展开侧边栏并不触发 active-leaf-change，
 * 没有任何后续事件来纠正它。
 *
 * 视图【活着】的时候收到 `setState` 也走同一条规则，理由相同：那条路上来的路径同样
 * 可能是存档回放（保存/恢复工作区、叶子被搬动），并不总是「谁明确要求换到这一篇」。
 *
 * 「固定显示一篇笔记」开着时正好反过来：那个开关的用途就是把导图钉在一篇上，存档说了算。
 *
 * 「笔记 → 导图」换形态不受这条规则影响——转换前会先把那篇笔记打开，
 * 换形态的那一刻它就是活动笔记，两个候选是同一个。
 *
 * @param restored 视图状态里存档的那一篇，没有就是 null
 * @param active 当前活动笔记，没有就是 null
 * @param lockFile 「固定显示一篇笔记」开关
 */
export function fileToShow<T>(restored: T | null, active: T | null, lockFile: boolean): T | null {
  return lockFile ? (restored ?? active) : (active ?? restored)
}
